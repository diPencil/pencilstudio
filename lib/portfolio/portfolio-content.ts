export const getWork = (slug: string): WorkCategory | undefined => {
  const normalized =
    slug === "websites"
      ? "website-development"
      : slug === "mobile-apps"
      ? "mobile-app-development"
      : slug === "social-media"
      ? "social-media-design"
      : slug;
  return (
    WORK_CATEGORIES.find((c) => c.slug === normalized || c.slug === slug) ||
    WORK_CATEGORIES[0]
  );
};
